"""Locks the Python packages of the runtimes to a tested set.

Freezes the installed runtimes of this Mac (Settings → Runtimes) and writes, per engine:
  engines/<engine>/constraints.txt   every package of the runtime at its exact version (also the ones that only
                                     come in through other packages, and ComfyUI's own), applied with `uv pip -c`
  engines/<engine>/requirements.txt  the direct requirements pinned to the same versions (comments kept)

A runtime is only locked after it was accepted: installed (or updated) on this Mac, the tests run, a picture or video
made with it. The lock is what users get; nothing newer reaches them before it went through that. See
docs/DEVELOPMENT.md, "Dependency updates".

    python3 tools/lock_runtimes.py [diffusers mlx comfyui]     default: all installed runtimes
"""
import datetime
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNTIMES = os.path.expanduser("~/Library/Application Support/VulKara/runtimes")
ENGINE = {"diffusers": "diffusers", "mlx": "mlx", "comfyui": "comfy"}
# tools of the developer, never part of a runtime (pytest gets installed to run the engine tests)
DEV_ONLY = {"pytest", "iniconfig", "pluggy"}
NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)(\[[^\]]*\])?")


def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def freeze(rt):
    uv = os.path.join(RUNTIMES, "bin", "uv")
    python = os.path.join(RUNTIMES, rt, "venv", "bin", "python")
    if not os.path.exists(python):
        return None
    out = subprocess.check_output([uv, "pip", "freeze", "--python", python], text=True)
    pins = {}
    for line in out.splitlines():
        if "==" in line and not line.startswith("#"):
            name, version = line.split("==", 1)
            if norm(name) not in DEV_ONLY:
                pins[norm(name)] = (name.strip(), version.strip())
    return pins


def pin_requirements(path, pins):
    """Every direct requirement to `name==version` from the frozen set; its comment stays."""
    lines = []
    for raw in open(path, encoding="utf-8").read().splitlines():
        body, _, comment = raw.partition("#")
        m = NAME.match(body)
        if not body.strip() or not m:
            lines.append(raw)
            continue
        name, extras = m.group(1), m.group(2) or ""
        if norm(name) not in pins:
            raise SystemExit(f"{path}: {name} is required but not installed in the runtime; install or update it first")
        marker = body.split(";", 1)[1].strip() if ";" in body else ""
        pinned = f"{name}{extras}=={pins[norm(name)][1]}" + (f"; {marker}" if marker else "")
        lines.append(pinned + (f"  #{comment}" if comment else ""))
    open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")


def main(names):
    today = datetime.date.today().isoformat()
    for rt in names:
        pins = freeze(rt)
        if pins is None:
            print(f"{rt}: not installed, skipped")
            continue
        engine = os.path.join(ROOT, "engines", ENGINE[rt])
        key = ", ".join(f"{n} {v}" for k, (n, v) in sorted(pins.items()) if k in ("torch", "diffusers", "mflux", "mlx", "transformers", "pillow"))
        head = [
            f"# Locked set of the {rt} runtime (generated by tools/lock_runtimes.py, {today}).",
            f"# {len(pins)} packages; key: {key}.",
            "# Applied with `uv pip install -c` on every install and update. Change it only through an accepted",
            "# dependency update (docs/DEVELOPMENT.md, Dependency updates), never by hand.",
        ]
        body = [f"{n}=={v}" for _, (n, v) in sorted(pins.items())]
        open(os.path.join(engine, "constraints.txt"), "w", encoding="utf-8").write("\n".join(head + body) + "\n")
        pin_requirements(os.path.join(engine, "requirements.txt"), pins)
        print(f"{rt}: {len(pins)} packages locked -> engines/{ENGINE[rt]}/constraints.txt")


if __name__ == "__main__":
    main(sys.argv[1:] or list(ENGINE))
